// Derive SDK types and compact runtime codecs from the Rust-owned OpenRPC fixture.
import { readFileSync, writeFileSync } from "node:fs";
import { nativeSpecDigest } from "./native-spec-digest.mjs";
import { format, resolveConfig } from "prettier";
async function emit(file, content) {
  const path = new URL(file, import.meta.url);
  const output = await format(content, {
    ...(await resolveConfig(path.pathname)),
    filepath: path.pathname,
  });
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== output)
      throw new Error(`Stale generated native RPC file: ${path.pathname}`);
  } else writeFileSync(path, output);
}
const spec = JSON.parse(
  readFileSync(
    new URL("../specs/native-openrpc.json", import.meta.url),
    "utf8",
  ),
);
const provenance = JSON.parse(
  readFileSync(
    new URL("../specs/native-openrpc.provenance.json", import.meta.url),
    "utf8",
  ),
);
if (
  !/^[0-9a-f]{40}$/.test(provenance.commit) ||
  nativeSpecDigest(spec) !== provenance.sha256
)
  throw new Error(
    "Native fixture differs from its recorded owner provenance; regenerate from Rust",
  );
if (spec.info.version !== "14.1.1" || spec.methods.length !== 20)
  throw new Error("Expected the reviewed wire-14 method catalog");
function tagField(s) {
  const variants = s.oneOf ?? s.anyOf;
  return variants?.length
    ? Object.keys(variants[0].properties ?? {}).find((key) =>
        variants.every((v) => typeof v.properties?.[key]?.const === "string"),
      )
    : undefined;
}
const schemas = Object.fromEntries(
  Object.entries(spec.components.schemas).map(([name, s]) => [
    name,
    compact(s, name),
  ]),
);
function isHex(s) {
  return s.pattern?.startsWith("^0x");
}
function extensible(s) {
  return s["x-extensible"] === true;
}
function type(s, key = "") {
  if (s["x-base58-bytes"]) return "Uint8Array";
  if (s.$ref) return "Rpc" + s.$ref.split("/").at(-1);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(JSON.stringify).join(" | ");
  if (s["x-integer-minimum"] !== undefined) return "bigint";
  if (isHex(s)) return s["x-opaque-string"] ? "string" : "Uint8Array";
  if (s.oneOf || s.anyOf)
    return `(${(s.oneOf ?? s.anyOf).map((v) => type(v, key)).join(" | ")}${extensible(s) ? " | UnsupportedRpcValue" : ""})`;
  if (s.type === "object" || s.properties)
    return `{ ${Object.entries(s.properties ?? {})
      .map(
        ([k, v]) =>
          `${JSON.stringify(k)}${s.required?.includes(k) ? "" : "?"}: ${type(v, k)};`,
      )
      .join(" ")} }`;
  if (s.type === "array") return `(${type(s.items)})[]`;
  if (s.type === "integer" || s.type === "number") return "number";
  if (["string", "boolean", "null"].includes(s.type)) return s.type;
  throw new Error(`Unsupported schema: ${JSON.stringify(s)}`);
}
const special = new Set([
  "getEvents",
  "getTransactionsByRootAddress",
  "getTransactionsByBlock",
]);
const methods = Object.fromEntries(
  spec.methods.map((m) => [
    m.name,
    {
      params: {
        type: "object",
        additionalProperties: false,
        properties: Object.fromEntries(
          m.params.map((p) => [p.name, compact(p.schema, p.name)]),
        ),
        required: m.params.filter((p) => p.required).map((p) => p.name),
      },
      result: compact(m.result.schema),
      paged: special.has(m.name),
    },
  ]),
);
let output =
  '// Generated by scripts/generate-native-rpc.mjs from the Rust-owned native OpenRPC fixture.\n// Do not edit.\nimport type { UnsupportedRpcValue } from "./codec.js";\n';
for (const [name, s] of Object.entries(schemas))
  output += `export type Rpc${name} = ${name.startsWith("Base58_") ? "Uint8Array" : type(s)};\n`;
output += "export interface RpcRequests {\n";
for (const [name, m] of Object.entries(methods)) {
  const schema = structuredClone(m.params);
  let suffix = "";
  if (special.has(name)) {
    const start = type(schema.properties.start);
    delete schema.properties.start;
    delete schema.properties.cursor;
    suffix = ` & ({ start: ${start}; cursor?: never } | { cursor: string; start?: never })`;
  }
  output += `${JSON.stringify(name)}: ${type(schema)}${suffix};\n`;
}
output += "}\nexport interface RpcResults {\n";
for (const [name, m] of Object.entries(methods))
  output += `${JSON.stringify(name)}: ${type(m.result)};\n`;
output += "}\n";
function compact(s, key = "") {
  const keep = new Set([
    "$ref",
    "const",
    "enum",
    "type",
    "properties",
    "required",
    "additionalProperties",
    "items",
    "anyOf",
    "oneOf",
    "minimum",
    "maximum",
    "minLength",
    "maxLength",
    "minItems",
    "maxItems",
    "pattern",
    "x-integer-minimum",
    "x-integer-maximum",
    "x-tag",
    "x-extensible",
    "x-base58-bytes",
    "x-opaque-string",
    "x-forbidden",
    "dependencies",
  ]);
  const result = Object.fromEntries(
    Object.entries(s)
      .filter(([k]) => keep.has(k))
      .map(([k, v]) => [
        k,
        k === "properties"
          ? Object.fromEntries(
              Object.entries(v).map(([a, b]) => [a, compact(b, a)]),
            )
          : k === "items"
            ? compact(v)
            : ["anyOf", "oneOf"].includes(k)
              ? v.map((x) => compact(x, key))
              : v,
      ]),
  );
  const tag = tagField(s);
  if (tag) result["x-tag"] = tag;
  if (s.anyOf && (tag || s.anyOf.every((v) => v.enum)))
    result["x-extensible"] = true;
  if (isHex(s) && ["cursor", "nextCursor"].includes(key))
    result["x-opaque-string"] = true;
  if (key.startsWith("Base58_")) {
    if (!s.description?.includes("exactly 32 bytes"))
      throw new Error(`Unknown base58 width for ${key}`);
    result["x-base58-bytes"] = 32;
  }
  return result;
}
// Resolve the owner's error definitions and flatten its small allOf constraint subset.
// Fail generation if the owner adds a constraint we do not understand.
function errorSchema(s, definitions, key = "") {
  if (s.$ref) {
    const name = s.$ref.split("/").at(-1);
    if (!definitions[name]) throw new Error(`Missing error definition ${name}`);
    if (name.endsWith("Reason")) return { type: "string" }; // Future reasons stay strings.
    const value = errorSchema(definitions[name], definitions, name);
    if (name === "ExecutorBoundDetail") value["x-extensible"] = true;
    return value;
  }
  let result = { ...s };
  delete result.allOf;
  for (const part of s.allOf ?? []) {
    if (Object.keys(part).length !== 1)
      throw new Error(
        `Unsupported mixed error constraint ${JSON.stringify(part)}`,
      );
    if (part.$ref) {
      const other = errorSchema(part, definitions);
      result = {
        ...other,
        ...result,
        properties: { ...other.properties, ...result.properties },
        required: [
          ...new Set([...(other.required ?? []), ...(result.required ?? [])]),
        ],
      };
      if (!Object.keys(result.properties).length) delete result.properties;
      if (!result.required.length) delete result.required;
    } else if (part.not?.required?.length === 1) {
      result["x-forbidden"] = [
        ...(result["x-forbidden"] ?? []),
        part.not.required[0],
      ];
    } else if (part.required)
      result.required = [
        ...new Set([...(result.required ?? []), ...part.required]),
      ];
    else if (part.properties)
      result.properties = { ...result.properties, ...part.properties };
    else if (part.dependencies) result.dependencies = part.dependencies;
    else
      throw new Error(`Unsupported error constraint ${JSON.stringify(part)}`);
  }
  if (result.properties)
    result.properties = Object.fromEntries(
      Object.entries(result.properties).map(([k, v]) => [
        k,
        errorSchema(v, definitions, k),
      ]),
    );
  if (result.items) result.items = errorSchema(result.items, definitions);
  for (const field of ["oneOf", "anyOf"])
    if (result[field])
      result[field] = result[field].map((v) => errorSchema(v, definitions));
  return compact(result, key);
}
const errorMethods = Object.fromEntries(
  spec.methods.map((m) => [
    m.name,
    m.errors.map((ref) => {
      const name = ref.$ref.split("/").at(-1);
      const original = m["x-data-schema"][name];
      return {
        code: spec.components.errors[name].code,
        schema: errorSchema(original, original.definitions),
      };
    }),
  ]),
);
const errorKinds = new Map();
for (const entries of Object.values(errorMethods))
  for (const entry of entries)
    for (const variant of entry.schema.oneOf) {
      // Types describe the union; method-specific runtime schemas restrict evidence.
      errorKinds.set(variant.properties.kind.const, variant);
    }
output +=
  "export type RpcErrorData = " +
  [...errorKinds.values()].map((v) => type(v)).join(" | ") +
  ";\n";
const runtime = {
  schemas,
  methods,
  errors: errorMethods,
};
